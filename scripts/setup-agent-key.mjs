// Splits the web server's signer off the deployer key (audit finding F-02).
//
//   node scripts/setup-agent-key.mjs            1st run: generates STOCK_AGENT_PRIVATE_KEY in .env.local, prints the address
//                                               2nd run (after funding it): grants the agent its narrow roles
//   node scripts/setup-agent-key.mjs --no-mint  skip MINT_ROLE grants (disables the faucet for this key)
//
// Roles granted to the agent, signed by DEPLOYER_PRIVATE_KEY (run locally, never on the server):
//   - StockExchange.setAgentAuthorization(agent, true)  -> setPrices
//   - flagship vault.setAgentAuthorization(agent, true) -> rebalance
//   - ETFFactory.setDefaultAgent(agent)                 -> agent on ETFs created from now on
//   - MINT_ROLE on tUSDC and every stock token          -> /api/stocks/faucet
// The agent does NOT get exchange/factory ownership, token admin, or vault ownership (so `set-weights` on the
// flagship stays with the deployer). Re-runnable: grants that already exist are skipped.
//
// Afterwards, on Vercel: set STOCK_AGENT_PRIVATE_KEY, and delete DEPLOYER_PRIVATE_KEY.
import fs from 'node:fs';
import path from 'node:path';
import { ethers } from 'ethers';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const envPath = path.join(root, '.env.local');
const statePath = path.join(root, 'src/config/deployments/base-sepolia.json');
const NO_MINT = process.argv.includes('--no-mint');
const CHUNK = 5; // the public Base Sepolia RPC allows ~25 requests/s
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function withRetry(fn, tries = 5) {
  for (let i = 1; ; i++) {
    try {
      return await fn();
    } catch (e) {
      if (i >= tries || !/request limit|rate limit|429|timeout/i.test(JSON.stringify(e.info ?? e.message))) throw e;
      await sleep(1000 * i);
    }
  }
}
const MINT_ROLE = ethers.id('MINT_ROLE');

for (const line of fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8').split('\n') : []) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
}
if (!process.env.DEPLOYER_PRIVATE_KEY) throw new Error('DEPLOYER_PRIVATE_KEY missing from .env.local');

if (!process.env.STOCK_AGENT_PRIVATE_KEY) {
  const w = ethers.Wallet.createRandom();
  fs.appendFileSync(envPath, `\n# Base Sepolia stock agent (price sync, rebalance, faucet). Generated by scripts/setup-agent-key.mjs\nSTOCK_AGENT_PRIVATE_KEY=${w.privateKey}\n`);
  console.log(`Generated STOCK_AGENT_PRIVATE_KEY in .env.local\n\n  Agent address: ${w.address}\n`);
  console.log('Fund it with Base Sepolia ETH (0.01 ETH is plenty), then run this script again.');
  process.exit(0);
}

const provider = new ethers.JsonRpcProvider(process.env.BASE_SEPOLIA_RPC_URL || 'https://sepolia.base.org');
if ((await provider.getNetwork()).chainId !== 84532n) throw new Error('RPC is not Base Sepolia');
const deployerWallet = new ethers.Wallet(process.env.DEPLOYER_PRIVATE_KEY, provider);
const deployer = new ethers.NonceManager(deployerWallet);
const agent = new ethers.Wallet(process.env.STOCK_AGENT_PRIVATE_KEY).address;
if (agent.toLowerCase() === deployerWallet.address.toLowerCase()) throw new Error('STOCK_AGENT_PRIVATE_KEY is the deployer key; generate a new one');

const state = JSON.parse(fs.readFileSync(statePath, 'utf8'));
const exchangeAddr = state.exchange?.address;
const factoryAddr = state.factory?.address;
const vaultAddr = state.vault?.address;
if (!exchangeAddr || !factoryAddr) throw new Error('Exchange/factory not in the deployment file; deploy first');

console.log(`Deployer ${deployerWallet.address}  Agent ${agent}  agent balance ${ethers.formatEther(await provider.getBalance(agent))} ETH`);

async function send(label, txPromise) {
  const r = await (await txPromise).wait();
  console.log(`  ✓ ${label}  ${r.hash}`);
}

const agentAbi = ['function authorizedAgents(address) view returns (bool)', 'function setAgentAuthorization(address agent, bool authorized)'];
const exchange = new ethers.Contract(exchangeAddr, agentAbi, deployer);
if (!(await exchange.authorizedAgents(agent))) await send('exchange agent', exchange.setAgentAuthorization(agent, true));
else console.log('  = exchange agent');

if (vaultAddr) {
  const vault = new ethers.Contract(vaultAddr, agentAbi, deployer);
  if (!(await vault.authorizedAgents(agent))) await send('flagship vault agent', vault.setAgentAuthorization(agent, true));
  else console.log('  = flagship vault agent');
}

const factory = new ethers.Contract(factoryAddr, ['function defaultAgent() view returns (address)', 'function setDefaultAgent(address)'], deployer);
if ((await factory.defaultAgent()).toLowerCase() !== agent.toLowerCase()) await send('factory default agent', factory.setDefaultAgent(agent));
else console.log('  = factory default agent');

if (!NO_MINT) {
  const tokens = [state.cashToken, ...(state.stocks ?? [])].filter((t) => t?.address);
  const roleAbi = ['function hasRole(bytes32 role, address account) view returns (bool)', 'function grantRole(bytes32 role, address account)'];
  const missing = [];
  for (const t of tokens) if (!(await withRetry(() => new ethers.Contract(t.address, roleAbi, provider).hasRole(MINT_ROLE, agent)))) missing.push(t);
  console.log(`  MINT_ROLE missing on ${missing.length}/${tokens.length} tokens`);
  for (let i = 0; i < missing.length; i += CHUNK) {
    const batch = missing.slice(i, i + CHUNK);
    // Explicit nonces: a retried send reuses its nonce, so a rate-limited attempt never leaves a gap.
    let nonce = await withRetry(() => deployerWallet.getNonce('pending'));
    const txs = [];
    for (const t of batch) {
      const n = nonce++;
      txs.push(await withRetry(() => new ethers.Contract(t.address, roleAbi, deployerWallet).grantRole(MINT_ROLE, agent, { gasLimit: 120_000, nonce: n })));
    }
    await Promise.all(txs.map((tx) => withRetry(() => tx.wait())));
    console.log(`  ✓ MINT_ROLE ${i + 1}-${i + batch.length}`);
    await sleep(400);
  }
}

console.log('\nDone. Next: set STOCK_AGENT_PRIVATE_KEY in the Vercel project env and delete DEPLOYER_PRIVATE_KEY there.');
