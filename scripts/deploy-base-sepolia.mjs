// Deploys the user-created ETF platform to Base Sepolia (chain 84532).
//
//   node scripts/deploy-base-sepolia.mjs           core + wiring + flagship (each step skipped when done)
//   node scripts/deploy-base-sepolia.mjs --core    only tUSDC, StockExchange, vault implementation, ETFFactory
//
// Order of a fresh deploy:
//   1. this script --core      -> tUSDC, StockExchange, StockBasketVault implementation, ETFFactory
//   2. scripts/create-stock-tokens.mjs  -> B-20 stock tokens (grants the exchange MINT/BURN in initCalls)
//   3. this script             -> grants any missing exchange roles, lists every stock, seeds prices,
//                                 creates the flagship "BEAVII Magnificent 7" ETF through the factory
// Progress lives in src/config/deployments/base-sepolia.json. The file is re-read before every save and only
// this script's keys are written, so it can run alongside create-stock-tokens.mjs (which owns `stocks`).
//
// Env (.env.local): DEPLOYER_PRIVATE_KEY (generated on first run if missing), BASE_SEPOLIA_RPC_URL,
//   AGENT_WALLET_ADDRESS (price/rebalance bot, default deployer), PROTOCOL_TREASURY_ADDRESS (default deployer),
//   PROTOCOL_FEE_BPS (protocol share of ETF fees, default 2000 = 20%, max 3000)
import fs from 'node:fs';
import path from 'node:path';
import { ethers } from 'ethers';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const envPath = path.join(root, '.env.local');
const outPath = path.join(root, 'src/config/deployments/base-sepolia.json');
const CHAIN_ID = 84532n;
const B20_FACTORY = '0xB20f000000000000000000000000000000000000';
const SALT_PREFIX = process.env.B20_SALT_PREFIX || 'beavii-stocks-v1';
const FLAGSHIP = { name: 'BEAVII Magnificent 7', symbol: 'bMAG7', symbols: ['AAPLc', 'MSFTc', 'NVDAc', 'GOOGLc', 'AMZNc', 'METAc', 'TSLAc'] };
const FLAGSHIP_FEES = { managementFeeBps: 50, entryFeeBps: 0, exitFeeBps: 0 }; // 0.50%/yr
const LIST_BATCH = 100;
const ROLE = (n) => ethers.id(n);
const MAX_SUPPLY_CAP = (1n << 128n) - 1n;
const CORE_ONLY = process.argv.includes('--core');

// ---------------------------------------------------------------- env
function loadEnv() {
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
}
loadEnv();

if (!process.env.DEPLOYER_PRIVATE_KEY) {
  const w = ethers.Wallet.createRandom();
  fs.appendFileSync(envPath, `\n# Base Sepolia deployer (testnet only, generated by scripts/deploy-base-sepolia.mjs)\nDEPLOYER_PRIVATE_KEY=${w.privateKey}\n`);
  console.log(`Generated a new testnet deployer key and saved it to .env.local\n\n  Deployer address: ${w.address}\n`);
  console.log('Fund it with Base Sepolia ETH (0.02 ETH is plenty), then run this script again:');
  console.log('  https://portal.cdp.coinbase.com/onchain-tools/faucet');
  process.exit(0);
}

const provider = new ethers.JsonRpcProvider(process.env.BASE_SEPOLIA_RPC_URL || 'https://sepolia.base.org');
const wallet = new ethers.NonceManager(new ethers.Wallet(process.env.DEPLOYER_PRIVATE_KEY, provider));
const deployer = await wallet.getAddress();
const agentWallet = process.env.AGENT_WALLET_ADDRESS || deployer;
const treasury = process.env.PROTOCOL_TREASURY_ADDRESS || deployer;
const protocolFeeBps = Number(process.env.PROTOCOL_FEE_BPS ?? 2000);

const net = await provider.getNetwork();
if (net.chainId !== CHAIN_ID) throw new Error(`RPC is chain ${net.chainId}, expected Base Sepolia ${CHAIN_ID}`);
const bal = await provider.getBalance(deployer);
console.log(`Deployer ${deployer}  balance ${ethers.formatEther(bal)} ETH`);
if (bal < ethers.parseEther('0.002')) {
  console.log('Balance too low. Fund it at https://portal.cdp.coinbase.com/onchain-tools/faucet and re-run.');
  process.exit(1);
}

// ---------------------------------------------------------------- state (merge-on-save)
const readState = () => (fs.existsSync(outPath) ? JSON.parse(fs.readFileSync(outPath, 'utf8')) : {});
const mine = {}; // keys this script owns
let state = readState();
const save = (patch) => {
  Object.assign(mine, patch);
  state = { ...readState(), ...mine };
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, JSON.stringify(state, null, 2) + '\n');
};
save({ network: 'base-sepolia', chainId: Number(CHAIN_ID), explorer: 'https://sepolia.basescan.org', deployer, agentWallet, b20Factory: B20_FACTORY });

// ---------------------------------------------------------------- ABIs
const artifact = (n) => JSON.parse(fs.readFileSync(path.join(root, `src/lib/abis/${n}.json`), 'utf8'));
const [exchangeArt, vaultArt, factoryArt] = ['StockExchange', 'StockBasketVault', 'ETFFactory'].map(artifact);
const b20FactoryAbi = [
  'function createB20(uint8 variant, bytes32 salt, bytes params, bytes[] initCalls) payable returns (address)',
  'function getB20Address(uint8 variant, address sender, bytes32 salt) view returns (address)',
  'function isB20Initialized(address token) view returns (bool)',
];
const b20Abi = [
  'function grantRole(bytes32 role, address account)',
  'function hasRole(bytes32 role, address account) view returns (bool)',
  'function updateSupplyCap(uint256 newSupplyCap)',
];
const b20 = new ethers.Interface(b20Abi);
const b20Factory = new ethers.Contract(B20_FACTORY, b20FactoryAbi, wallet);
const isLive = async (addr) => Boolean(addr) && (await provider.getCode(addr)) !== '0x';

async function send(label, txPromise) {
  const tx = await txPromise;
  const r = await tx.wait();
  console.log(`  ✓ ${label}  ${r.hash}`);
  return r;
}

async function deploy(label, art, args) {
  const c = await new ethers.ContractFactory(art.abi, art.bytecode, wallet).deploy(...args);
  await c.waitForDeployment();
  console.log(`  ✓ ${label} ${c.target}`);
  return { address: c.target, deployTx: c.deploymentTransaction().hash };
}

// ---------------------------------------------------------------- 1. cash token
console.log('\n[1/6] tUSDC (B-20 cash token)');
const cash = state.cashToken?.address ? state.cashToken : { symbol: 'tUSDC', name: 'Test USD Coin (Base Sepolia)', decimals: 6 };
{
  const salt = ethers.id(`${SALT_PREFIX}:${cash.symbol}`);
  const predicted = await b20Factory.getB20Address(0, deployer, salt);
  if (!(await b20Factory.isB20Initialized(predicted).catch(() => false))) {
    const params = ethers.AbiCoder.defaultAbiCoder().encode(
      ['tuple(uint8 version,string name,string symbol,address initialAdmin,uint8 decimals)'],
      [[1, cash.name, cash.symbol, deployer, cash.decimals]],
    );
    const initCalls = [
      b20.encodeFunctionData('updateSupplyCap', [MAX_SUPPLY_CAP]),
      b20.encodeFunctionData('grantRole', [ROLE('MINT_ROLE'), deployer]),
      b20.encodeFunctionData('grantRole', [ROLE('BURN_ROLE'), deployer]),
    ];
    await send(`create ${cash.symbol} -> ${predicted}`, b20Factory.createB20(0, salt, params, initCalls));
  } else console.log(`  = ${cash.symbol} ${predicted}`);
  cash.address = predicted;
  save({ cashToken: cash });
}

// ---------------------------------------------------------------- 2. exchange
console.log('\n[2/6] StockExchange (shared NAV feed + mint/burn venue)');
if (!(await isLive(state.exchange?.address))) save({ exchange: await deploy('StockExchange', exchangeArt, [cash.address, agentWallet, deployer]) });
else console.log(`  = StockExchange ${state.exchange.address}`);
const exchange = new ethers.Contract(state.exchange.address, exchangeArt.abi, wallet);

// ---------------------------------------------------------------- 3. implementation + factory
console.log('\n[3/6] ETFFactory');
let factoryState = state.factory ?? {};
if (!(await isLive(factoryState.implementation))) {
  const impl = await deploy('StockBasketVault implementation', vaultArt, []);
  factoryState = { implementation: impl.address };
}
if (!(await isLive(factoryState.address))) {
  const f = await deploy('ETFFactory', factoryArt, [factoryState.implementation, exchange.target, treasury, protocolFeeBps, agentWallet, deployer]);
  factoryState = { ...factoryState, ...f, treasury, protocolFeeBps };
} else console.log(`  = ETFFactory ${factoryState.address}`);
save({ factory: factoryState });
const factory = new ethers.Contract(factoryState.address, factoryArt.abi, wallet);
if ((await exchange.factory()).toLowerCase() !== factory.target.toLowerCase()) await send('exchange.setFactory', exchange.setFactory(factory.target));

// ---------------------------------------------------------------- 4. exchange roles
console.log('\n[4/6] grant exchange MINT/BURN');
const stocks = readState().stocks ?? [];
async function grantExchange(tok) {
  const c = new ethers.Contract(tok.address, b20Abi, wallet);
  for (const r of ['MINT_ROLE', 'BURN_ROLE']) {
    if (!(await c.hasRole(ROLE(r), exchange.target))) await send(`${tok.testSymbol || tok.symbol} ${r}`, c.grantRole(ROLE(r), exchange.target));
  }
}
await grantExchange(cash);
if (CORE_ONLY) {
  console.log(`\nCore deployed. Exchange: ${exchange.target}  Factory: ${factory.target}`);
  console.log('Next: node scripts/create-stock-tokens.mjs, then re-run this script without --core.');
  process.exit(0);
}
if (!stocks.length) {
  console.log('  No stocks in the deployment file yet. Run scripts/create-stock-tokens.mjs, then re-run this script.');
  process.exit(0);
}
for (const s of stocks) await grantExchange(s);

// ---------------------------------------------------------------- 5. list stocks + seed prices
console.log(`\n[5/6] list ${stocks.length} stocks on the exchange`);
const unlisted = [];
for (const s of stocks) if (!(await exchange.isListed(s.address))) unlisted.push(s.address);
for (let i = 0; i < unlisted.length; i += LIST_BATCH) {
  const batch = unlisted.slice(i, i + LIST_BATCH);
  await send(`setListed ${i + 1}-${i + batch.length}`, exchange.setListed(batch, true));
}
const toPrice8 = (n) => ethers.parseUnits(Number(n).toFixed(8), 8);
const priced = stocks.filter((s) => Number(s.priceUsd ?? s.navPrice) > 0);
const unpricedOnchain = [];
for (const s of priced) if ((await exchange.price(s.address)) === 0n) unpricedOnchain.push(s);
for (let i = 0; i < unpricedOnchain.length; i += LIST_BATCH) {
  const batch = unpricedOnchain.slice(i, i + LIST_BATCH);
  await send(`seed prices ${i + 1}-${i + batch.length}`, exchange.setPrices(batch.map((s) => s.address), batch.map((s) => toPrice8(s.priceUsd ?? s.navPrice))));
}

// ---------------------------------------------------------------- 6. flagship ETF
console.log(`\n[6/6] flagship ETF ${FLAGSHIP.symbol}`);
if (!(await isLive(state.vault?.address))) {
  const basket = FLAGSHIP.symbols.map((sym) => stocks.find((s) => s.symbol === sym)).filter(Boolean);
  if (basket.length !== FLAGSHIP.symbols.length) throw new Error('Flagship stocks missing from the deployment file');
  const base = Math.floor(10_000 / basket.length);
  const weights = basket.map((_, i) => (i === 0 ? 10_000 - base * (basket.length - 1) : base));
  const params = {
    name: FLAGSHIP.name,
    symbol: FLAGSHIP.symbol,
    description: 'Equal-weight basket of the seven largest US tech stocks, as Base tokenized-stock mirrors.',
    feeRecipient: treasury,
    tokens: basket.map((s) => s.address),
    weights,
    fees: FLAGSHIP_FEES,
  };
  const r = await send('createETFFor', factory.createETFFor(params, deployer));
  const ev = r.logs.map((l) => { try { return factory.interface.parseLog(l); } catch { return null; } }).find((e) => e?.name === 'ETFCreated');
  save({
    vault: { address: ev.args.vault, name: FLAGSHIP.name, symbol: FLAGSHIP.symbol, deployTx: r.hash },
    basket: basket.map((s, i) => ({ symbol: s.symbol, address: s.address, weight: weights[i] })),
  });
} else console.log(`  = ${FLAGSHIP.symbol} ${state.vault.address}`);

save({ deployedAt: new Date().toISOString() });
console.log(`\nDone. Wrote ${path.relative(root, outPath)}`);
console.log(`Exchange: ${state.explorer}/address/${exchange.target}`);
console.log(`Factory:  ${state.explorer}/address/${factory.target}`);
console.log(`Flagship: ${state.explorer}/address/${state.vault.address}`);
